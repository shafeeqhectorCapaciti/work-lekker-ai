function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en" className="dark">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function CurrentPageTitle() {
  const pathname = useRouterState({ select: (s) => s.location.pathname });
  const item = NAV_ITEMS.find((i) => i.url === pathname);
  return (
    <span className="truncate text-sm font-medium text-foreground">
      {item?.title ?? "WorkLekker AI"}
    </span>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <SidebarProvider>
        <div className="flex min-h-screen w-full">
          <AppSidebar />
          <div className="flex min-w-0 flex-1 flex-col">
            <div
              role="note"
              className="flex items-center justify-center gap-2 border-b border-border bg-accent/40 px-4 py-2 text-center text-xs text-muted-foreground"
            >
              <ShieldCheck className="size-3.5 shrink-0 text-primary" />
              <span>
                <span className="font-semibold text-foreground">Responsible AI:</span>{" "}
                AI-generated content may require human review.
              </span>
            </div>
            <header className="sticky top-0 z-20 flex h-14 items-center gap-3 border-b border-border bg-background/80 px-4 backdrop-blur">
              <SidebarTrigger aria-label="Toggle sidebar" />
              <span className="h-5 w-px bg-border" aria-hidden />
              <CurrentPageTitle />
            </header>
            <main className="flex-1 px-4 py-6 md:px-8 md:py-8">
              <div className="mx-auto w-full max-w-6xl">
                <Outlet />
              </div>
            </main>
          </div>
        </div>
      </SidebarProvider>
      <Toaster position="bottom-right" />
    </QueryClientProvider>
  );
}
